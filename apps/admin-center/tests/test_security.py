def test_local_totp_setup_completes_login_and_remembered_session(client, app):
    with app.app_context():
        user = User(
            email="local-2fa@example.test",
            username="local.2fa",
            display_name="Local 2FA",
            auth_provider="local",
            password_hash=generate_password_hash("local-password-strong"),
            role="ipam_operator",
            active=True,
        )
        db.session.add(user)
        db.session.commit()
    response = client.post(
        "/local-login",
        data={"username": "local.2fa", "password": "local-password-strong", "remember": "on"},
    )
    assert response.headers["Location"].endswith("/2fa/setup")
    setup_response = client.get("/2fa/setup")
    assert setup_response.status_code == 200
    with app.app_context():
        user = User.query.filter_by(username="local.2fa").one()
        from geofeed_admin.two_factor import secret_for

        code = pyotp.TOTP(secret_for(user)).now()
    response = client.post("/2fa/setup", data={"code": code})
    assert response.status_code == 302
    assert response.headers["Location"].endswith("/")
    assert "geofeed_remember=" in response.headers.get("Set-Cookie", "")
    with client.session_transaction() as session:
        session.clear()
    response = client.get("/")
    assert response.status_code == 200


